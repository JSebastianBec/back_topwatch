-- It asks for the admin account's details, so no personal data is stored in this file.
-- Everything is applied or nothing is. It is safe to run it again.

\set ON_ERROR_STOP on

\prompt 'Admin email: ' admin_email
\prompt 'Admin nickname: ' admin_nickname
\prompt 'Admin password hash (starts with $2): ' admin_password_hash

BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_version VARCHAR(255);

CREATE TABLE IF NOT EXISTS content_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_reporter BIGINT NOT NULL REFERENCES users (id),
    target_type VARCHAR(255) NOT NULL CHECK (target_type IN ('WATCH_LIST', 'ITEM', 'USER')),
    target_id BIGINT NOT NULL,
    reason VARCHAR(255) NOT NULL CHECK (reason IN ('SPAM', 'OFFENSIVE', 'SEXUAL', 'VIOLENCE', 'COPYRIGHT', 'OTHER')),
    details TEXT,
    status VARCHAR(255) NOT NULL CHECK (status IN ('OPEN', 'RESOLVED')),
    creation_date TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS user_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user_blocker BIGINT NOT NULL REFERENCES users (id),
    id_user_blocked BIGINT NOT NULL REFERENCES users (id),
    creation_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE (id_user_blocker, id_user_blocked)
);

-- Admin account. If the email already exists, it keeps its password and becomes admin.
INSERT INTO users (email, nickname, password, role, terms_accepted_at, terms_version)
VALUES (:'admin_email', :'admin_nickname', :'admin_password_hash', 'ADMIN', now(), '1.0')
ON CONFLICT (email) DO UPDATE SET role = 'ADMIN';

COMMIT;

SELECT id, email, nickname, role FROM users WHERE email = :'admin_email';
